/**
 * The hospital's actual consulting faculty, taken from the OPD Doctor Schedule
 * board and the two "Doctors Available" / "Proudly Welcomes" flyers.
 *
 * Only what those sources state is recorded here. Qualifications and past
 * appointments appear on the six doctors the flyer lists them for; the rest
 * carry their department, designation and OPD timing and nothing more.
 * There are deliberately no ratings, review counts, fees or biographies —
 * inventing those for named, real clinicians would be misleading.
 *
 * `photo` is left unset until the hospital supplies portraits; the UI falls
 * back to an initials avatar.
 */

export type OpdWindow = "morning" | "evening" | "both" | "on-call";

export type Doctor = {
  slug: string;
  name: string;
  shortName: string;
  initials: string;
  /** Set once the hospital provides a portrait. */
  photo?: string;
  departmentSlug: string;
  /** Short department label used on cards. */
  specialty: string;
  /** Full department label. */
  specialtyLabel: string;
  /** Short designation for the card badge. */
  roleLabel: string;
  /** Full designation as printed. */
  designation: string;
  /** Only where the hospital has published it. */
  qualification?: string;
  /** Previous posts / fellowships, as printed. */
  credentials?: string[];
  days: string[];
  daysLabel: string;
  /** Consulting hours exactly as the schedule board states them. */
  opdTiming: string;
  /** Compact form for narrow cards. */
  opdShort: string;
  /** OPD room / chamber as assigned. */
  opdRoom: string;
  onCall: boolean;
  opdWindow: OpdWindow;
};

